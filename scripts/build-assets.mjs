import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = path.resolve(__dirname, '..');
const PUBLIC_DIR = path.join(ROOT_DIR, 'public');
const OUT_FILE = path.join(ROOT_DIR, 'src', 'assets-bundle.js');

const ASSET_SPECS = [
  { route: '/index.html', file: 'index.html', contentType: 'text/html; charset=utf-8' },
  { route: '/styles.css', file: 'styles.css', contentType: 'text/css; charset=utf-8' },
  { route: '/app.js', file: 'app.js', contentType: 'application/javascript; charset=utf-8' },
  { route: '/favicon.svg', file: 'favicon.svg', contentType: 'image/svg+xml' }
];

const entries = {};
for (const spec of ASSET_SPECS) {
  const fullPath = path.join(PUBLIC_DIR, spec.file);
  const body = fs.readFileSync(fullPath, 'utf8');
  entries[spec.route] = { contentType: spec.contentType, body };
  if (spec.route === '/index.html') {
    entries['/'] = { contentType: spec.contentType, body };
  }
}

const output = `// Auto-generated by scripts/build-assets.mjs — do not edit manually.
export const STATIC_ASSETS = ${JSON.stringify(entries, null, 2)};
`;

fs.writeFileSync(OUT_FILE, output, 'utf8');
console.log(`Generated ${path.relative(ROOT_DIR, OUT_FILE)} (${Object.keys(entries).length} routes)`);
